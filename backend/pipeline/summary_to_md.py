"""series_76_summary.pdf (has a text layer) -> Markdown, with no LLM.

Uses `pdftotext -layout` and rebuilds the structure from indentation:
headings (isolated line with no final punctuation), numbered lists, bullets (nested when they
hang off a numbered item) and continuation lines. Line breaks after a hyphen are joined
without a space ("90-" + "degree" -> "90-degree", "761A00-" + "11380000/A").

Usage: uv run python -m pipeline.summary_to_md [--pdf PATH] [--out PATH]
"""

from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

from app.config import PROCESSED_DIR, REPO_ROOT

NUMBERED = re.compile(r"^(\s*)(\d+)\.\s+(.*)$")
BULLET = re.compile(r"^(\s*)[•●▪]\s*(.*)$")
TERM = re.compile(r"^([^:]{2,60}:)\s*(.*)$")  # "Weatherproof: ..." -> bold term


def pdf_text(pdf: Path) -> list[str]:
    out = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True, capture_output=True, text=True)
    return out.stdout.replace("\f", "\n").splitlines()


def join(prev: str, nxt: str) -> str:
    nxt = nxt.strip()
    return prev + nxt if prev.endswith("-") else f"{prev} {nxt}"


def bold_term(text: str) -> str:
    m = TERM.match(text)
    return f"**{m.group(1)}** {m.group(2)}".rstrip() if m else text


def to_markdown(lines: list[str]) -> str:
    # Each item: [kind, text]  kind in {h1, h2, p, num, bullet, subbullet}
    items: list[list[str]] = []
    num_indent: int | None = None
    prev_blank = True

    for i, raw in enumerate(lines):
        if not raw.strip():
            prev_blank = True
            continue
        indent = len(raw) - len(raw.lstrip())
        text = raw.strip()
        next_blank = i + 1 >= len(lines) or not lines[i + 1].strip()

        if m := NUMBERED.match(raw):
            num_indent = indent
            items.append(["num", f"{m.group(2)}. {m.group(3).strip()}"])
        elif m := BULLET.match(raw):
            nested = num_indent is not None and indent > num_indent
            items.append(["subbullet" if nested else "bullet", m.group(2).strip()])
        elif prev_blank and next_blank and indent == 0 and not text.endswith((".", ",", ":", ";")):
            items.append(["h1" if not items else "h2", text])
            num_indent = None
        elif items and not prev_blank and items[-1][0] not in ("h1", "h2"):
            items[-1][1] = join(items[-1][1], text)  # continuation line
        else:
            items.append(["p", text])
            if indent == 0:
                num_indent = None
        prev_blank = False

    out: list[str] = []
    for kind, text in items:
        if kind in ("h1", "h2"):
            out += ["", f"{'#' if kind == 'h1' else '##'} {text}", ""]
        elif kind == "p":
            out += [text, ""]
        elif kind == "num":
            n, rest = text.split(". ", 1)
            out.append(f"{n}. **{rest}**" if rest.endswith(":") else text)
        elif kind == "bullet":
            out.append(f"- {bold_term(text)}")
        else:
            out.append(f"   - {bold_term(text)}")
    md = "\n".join(out).strip() + "\n"
    return re.sub(r"\n{3,}", "\n\n", md)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pdf", type=Path, default=REPO_ROOT / "docs" / "assesment" / "series_76_summary.pdf")
    parser.add_argument("--out", type=Path, default=PROCESSED_DIR / "series_76_summary.md")
    args = parser.parse_args()

    md = to_markdown(pdf_text(args.pdf))
    source = f"> Source: `{args.pdf.relative_to(REPO_ROOT)}` (generated by `backend/pipeline/summary_to_md.py`).\n\n"
    args.out.parent.mkdir(parents=True, exist_ok=True)
    md = md.replace("\n", "\n\n" + source, 1) if md.startswith("# ") else source + md
    args.out.write_text(re.sub(r"\n{3,}", "\n\n", md))
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
